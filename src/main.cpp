std::string replace_slashes(std::string_view raw) {
    std::string res{raw};
    std::replace(res.begin(), res.end(), '\\', '/');

    return res;
}

std::string_view trim(std::string_view sv) noexcept {
    const auto not_space = [](unsigned char c) { return std::isspace(c) == 0; };
    const auto begin = std::find_if(
         sv.begin()
        ,sv.end()
        ,[&](char c) { return not_space(static_cast<unsigned char>(c)); }
    );
    const auto end = std::find_if(
         sv.rbegin()
        ,sv.rend()
        ,[&](char c) { return not_space(static_cast<unsigned char>(c)); }
    ).base();

    if ( begin >= end ) {
        return {};
    }

    return std::string_view{std::addressof(*begin), static_cast<std::size_t>(end - begin)};
}

bool is_version_token(std::string_view tok) noexcept {
    if ( tok.empty() ) {
        return false;
    }

    if ( tok == ">=" || tok == "<=" || tok == "!=" || tok == ">" || tok == "<" || tok == "=" ) {
        return true;
    }

    return std::isdigit(static_cast<unsigned char>(tok.front())) != 0;
}

std::string_view strip_version_suffix(std::string_view tok) noexcept {
    if ( const auto pos = tok.find_first_of("><=!"); pos != std::string_view::npos ) {
        tok = tok.substr(0, pos);
    }

    return trim(tok);
}

bool is_separator(char c, bool comma) noexcept {
    if ( std::isspace(static_cast<unsigned char>(c)) != 0 ) {
        return true;
    }

    return comma && c == ',';
}

std::vector<std::string_view> split_tokens(std::string_view raw, bool comma) {
    std::vector<std::string_view> res;
    std::size_t i = 0;
    while ( i < raw.size() ) {
        while ( i < raw.size() && is_separator(raw[i], comma) ) {
            ++i;
        }

        if ( i >= raw.size() ) {
            break;
        }

        const auto start = i;

        while ( i < raw.size() && !is_separator(raw[i], comma) ) {
            ++i;
        }

        auto tok = raw.substr(start, i - start);
        if ( comma ) {
            tok = strip_version_suffix(tok);

            if ( tok.empty() || is_version_token(tok) ) {
                continue;
            }
        }

        res.push_back(tok);
    }

    return res;
}

std::vector<std::string_view> split_requires(std::string_view raw) {
    return split_tokens(raw, true);
}

std::vector<std::string_view> split_flags(std::string_view raw) {
    return split_tokens(raw, false);
}

template<typename Dst, typename Src>
void append_unique(std::vector<Dst> *dst, const std::vector<Src> &src) {
    for ( const auto &item: src ) {
        if ( std::find(dst->begin(), dst->end(), item) == dst->end() ) {
            dst->emplace_back(item);
        }
    }
}

std::string join_flags(const std::vector<std::string> &flags) {
    std::string res;
    for ( const auto &flag: flags ) {
        if ( !res.empty() ) {
            res.push_back(' ');
        }

        res += flag;
    }

    return res;
}

struct string_hash {
    using is_transparent = void;

    std::size_t operator()(std::string_view text) const noexcept
    { return std::hash<std::string_view>{}(text); }
};

struct string_equal {
    using is_transparent = void;

    bool operator()(std::string_view left, std::string_view right) const noexcept
    { return left == right; }
};

using string_set = std::unordered_set<std::string, string_hash, string_equal>;
using string_map = std::unordered_map<
     std::string
    ,std::string
    ,string_hash
    ,string_equal
>;

struct pc_file {
    std::filesystem::path path;
    string_map vars;
    string_map keys;
};

std::string normalize_pc_path(std::string_view raw) {
    if ( auto s = replace_slashes(raw); s.empty() ) {
        return s;
    } else {
        const auto norm = std::filesystem::path{s}.lexically_normal();
        auto res = replace_slashes(norm.generic_string());
        while ( res.size() > 1 && res.back() == '/' ) {
            res.pop_back();
        }

        return res;
    }
}

std::string pcfiledir_of(const std::filesystem::path &pc_path) {
    return normalize_pc_path(pc_path.parent_path().generic_string());
}

std::string expand_vars(
     std::string_view raw
    ,const pc_file &pc
    ,string_set *stack
);

std::string expand_one(
     std::string_view name
    ,const pc_file &pc
    ,string_set *stack)
{
    if ( stack->count(name) != 0 ) {
        return {};
    }

    stack->insert(std::string{name});

    std::string_view raw;
    if ( auto it = pc.vars.find(name); it != pc.vars.end() ) {
        raw = it->second;
    }

    auto res = expand_vars(raw, pc, stack);
    stack->erase(name);

    return res;
}

std::string expand_vars(
     std::string_view raw
    ,const pc_file &pc
    ,string_set *stack)
{
    std::string res;
    res.reserve(raw.size());
    for ( std::size_t i = 0; i < raw.size(); ) {
        if ( raw[i] == '$' && i + 1 < raw.size() && raw[i + 1] == '{' ) {
            const auto end = raw.find('}', i + 2);

            if ( end == std::string_view::npos ) {
                res.append(raw.substr(i));

                break;
            }

            const auto name = raw.substr(i + 2, end - (i + 2));
            auto value = expand_one(name, pc, stack);

            if ( name == "pcfiledir" || name == "prefix" || name == "exec_prefix"
                || name == "libdir" || name == "includedir" || name == "sharedlibdir" )
            {
                value = normalize_pc_path(value);
            }

            res += value;
            i = end + 1;

            continue;
        }

        res.push_back(raw[i]);
        ++i;
    }

    return res;
}

std::string expand(std::string_view raw, const pc_file &pc) {
    string_set stack;
    return expand_vars(raw, pc, &stack);
}

std::expected<pc_file, std::string> parse_pc_file(const std::filesystem::path &path) {
    std::ifstream in{path};
    if ( !in ) {
        return std::unexpected{"can't read " + path.generic_string()};
    }

    pc_file res;
    res.path = path;
    res.vars.emplace("pcfiledir", pcfiledir_of(path));

    auto line = std::string{};
    while ( std::getline(in, line) ) {
        if ( !line.empty() && line.back() == '\r' ) {
            line.pop_back();
        }

        const auto body = trim(line);

        if ( body.empty() || body.front() == '#' ) {
            continue;
        }

        const auto colon = body.find(':');
        const auto eq = body.find('=');

        if ( colon != std::string_view::npos && (eq == std::string_view::npos || colon < eq) ) {
            const auto key = trim(body.substr(0, colon));
            const auto val = trim(body.substr(colon + 1));
            res.keys.insert_or_assign(std::string{key}, std::string{val});
        } else if ( eq != std::string_view::npos ) {
            const auto key = trim(body.substr(0, eq));
            const auto val = trim(body.substr(eq + 1));
            res.vars.insert_or_assign(std::string{key}, std::string{val});
        }
    }

    return res;
}

std::string_view map_get(const string_map &map, std::string_view name) noexcept {
    if ( const auto it = map.find(name); it == map.end() ) {
        return {};
    } else {
        return it->second;
    }
}

std::string key_or_empty(const pc_file &pc, std::string_view name) {
    return expand(map_get(pc.keys, name), pc);
}

void collect_flags(
     const pc_file &pc
    ,bool static_libs
    ,std::vector<std::string> *cflags
    ,std::vector<std::string> *libs)
{
    const auto cflags_text = key_or_empty(pc, "Cflags");
    const auto libs_text = key_or_empty(pc, "Libs");
    append_unique(cflags, split_flags(cflags_text));
    append_unique(libs, split_flags(libs_text));

    if ( static_libs ) {
        const auto cflags_priv = key_or_empty(pc, "Cflags.private");
        const auto libs_priv = key_or_empty(pc, "Libs.private");
        append_unique(cflags, split_flags(cflags_priv));
        append_unique(libs, split_flags(libs_priv));
    }
}

