std::vector<std::filesystem::path>
pc_search_dirs(const std::filesystem::path &tree) {
    std::vector<std::filesystem::path> dirs;
    auto add = [&](std::filesystem::path p) {
        p = p.lexically_normal();
        if ( p.empty() ) {
            return;
        }

        if ( std::find(dirs.begin(), dirs.end(), p) != dirs.end() ) {
            return;
        }

        dirs.push_back(std::move(p));
    };

    add(tree / k_pc_dir);
    add(tree / k_pc_mingw_triplet / k_pc_dir);

    std::error_code ec;
    for ( const auto &ent: std::filesystem::directory_iterator{tree, ec} ) {
        if ( ent.is_directory() ) {
            add(ent.path() / k_pc_dir);
        }
    }

#ifdef _WIN32
    constexpr char k_path_sep = ';';
#else
    constexpr char k_path_sep = ':';
#endif

    auto add_env = [&](const char *name) {
        const char *raw = ::getenv(name);

        if ( !raw || !*raw ) {
            return;
        }

        std::string_view sv{raw};
        while ( !sv.empty() ) {
            const auto pos = sv.find(k_path_sep);
            const auto part = pos == std::string_view::npos ? sv : sv.substr(0, pos);
            if ( !part.empty() ) {
                add(std::filesystem::path{std::string{part}});
            }

            if ( pos == std::string_view::npos ) {
                break;
            }

            sv.remove_prefix(pos + 1);
        }
    };

    add_env("PKG_CONFIG_LIBDIR");
    add_env("PKG_CONFIG_PATH");

    return dirs;
}

std::filesystem::path find_pc_file(
     std::string_view module
    ,const std::vector<std::filesystem::path> &dirs)
{
    const auto name = std::string{module} + ".pc";
    for ( const auto &dir: dirs ) {
        const auto cand = dir / name;

        if ( std::filesystem::is_regular_file(cand) ) {
            return cand;
        }
    }

    return {};
}

exit_code run_pc_command(
     const std::filesystem::path &tree
    ,const cmdargs::view_t<options> &view
    ,std::ostream &out
    ,std::ostream &err)
{
    if ( !view.module || view.module->empty() ) {
        err << "pkgconf: module name required\n";

        return exit_code::usage;
    }

    if ( !view.cflags.value_or(false) && !view.libs.value_or(false)
        && !view.modversion.value_or(false) && !view.exists.value_or(false) )
    {
        err << "pkgconf: specify --cflags, --libs, --modversion and/or --exists\n";

        return exit_code::usage;
    }

    const auto dirs = pc_search_dirs(tree);
    std::unordered_map<
         std::string
        ,pc_file
        ,string_hash
        ,string_equal
    > loaded;
    std::vector<std::string_view> order;
    string_set visiting;

    auto load = [&](auto &&self, std::string_view mod) -> bool {
        if ( loaded.count(mod) != 0 ) {
            return true;
        }

        if ( visiting.count(mod) != 0 ) {
            err << "pkgconf: circular Requires involving '" << mod << "'\n";

            return false;
        }

        const auto path = find_pc_file(mod, dirs);
        if ( path.empty() ) {
            if ( !view.exists.value_or(false) ) {
                err << "Package " << mod << " was not found in pkg-config search paths\n";
            }

            return false;
        }

        visiting.insert(std::string{mod});
        auto parsed = parse_pc_file(path);
        if ( !parsed ) {
            err << "pkgconf: " << parsed.error() << std::endl;
            visiting.erase(mod);

            return false;
        }

        const auto requires_text = expand(map_get(parsed->keys, "Requires"), *parsed);
        auto reqs = split_requires(requires_text);
        std::string private_text;

        if ( view.is_static.value_or(false) ) {
            private_text = expand(map_get(parsed->keys, "Requires.private"), *parsed);
            append_unique(&reqs, split_requires(private_text));
        }

        for ( const auto &dep: reqs ) {
            if ( !self(self, dep) ) {
                visiting.erase(mod);

                return false;
            }
        }

        visiting.erase(mod);
        const auto placed = loaded.emplace(std::string{mod}, std::move(*parsed)).first;
        order.push_back(placed->first);

        return true;
    };

    if ( !load(load, *view.module) ) {
        return exit_code::general_error;
    }

    if ( view.exists.value_or(false) && !view.cflags.value_or(false)
        && !view.libs.value_or(false) && !view.modversion.value_or(false) )
    {
        return exit_code::ok;
    }

    const auto &root = loaded.at(*view.module);
    if ( view.modversion.value_or(false) && !view.cflags.value_or(false)
        && !view.libs.value_or(false) )
    {
        out << key_or_empty(root, "Version") << std::endl;

        return exit_code::ok;
    }

    std::vector<std::string> cflags;
    std::vector<std::string> libs;

    for ( const auto &mod: order ) {
        collect_flags(loaded.at(mod), view.is_static.value_or(false), &cflags, &libs);
    }

    std::string line;
    if ( view.cflags.value_or(false) ) {
        line = join_flags(cflags);
    }

    if ( view.libs.value_or(false) ) {
        const auto libline = join_flags(libs);
        if ( !libline.empty() ) {
            if ( !line.empty() ) {
                line.push_back(' ');
            }

            line += libline;
        }
    }

    if ( view.modversion.value_or(false) ) {
        if ( !line.empty() ) {
            line.push_back(' ');
        }

        line += key_or_empty(root, "Version");
    }

    out << line << std::endl;

    return exit_code::ok;
}

std::filesystem::path default_prefix(const char *argv0) {
    std::error_code ec;
    auto exe = std::filesystem::absolute(argv0, ec);
    if ( ec ) {
        return std::filesystem::current_path();
    }

    auto parent = exe.parent_path();
    if ( parent.filename() == "bin" ) {
        return parent.parent_path();
    }

    return parent;
}

/*************************************************************************************************/

int main(int argc, char **argv) {
    std::string error;
    options opts{};
    const auto args = cmdargs::parse_args(
         &error
        ,argc
        ,argv
        ,opts
    );

    if ( !error.empty() ) {
        std::cerr << error << std::endl;

        return static_cast<int>(exit_code::usage);
    }

    if ( cmdargs::is_help_requested(std::cout, argv[0], args) ) {
        return static_cast<int>(exit_code::ok);
    }

    const auto view = cmdargs::make_view(args, opts);
    const std::filesystem::path prefix = view.prefix.has_value()
        ? std::filesystem::path{*view.prefix}
        : default_prefix(argc > 0 ? argv[0] : "pkgconf")
    ;

    return static_cast<int>(run_pc_command(
         prefix
        ,view
        ,std::cout
        ,std::cerr
    ));
}

